-- 回填 poems.author_id（根据 poems.author = authors.name 匹配）
-- 先处理完全匹配的情况
UPDATE poems p
SET author_id = a.id
FROM authors a
WHERE p.author_id IS NULL
  AND p.author = a.name;

-- 如果 poems.author 是繁体，尝试匹配 authors.name_traditional
UPDATE poems p
SET author_id = a.id
FROM authors a
WHERE p.author_id IS NULL
  AND p.author = a.name_traditional;

-- 回填 authors.dynasty：从 poems 表的 dynasty 字段（如果 poems 有值的话）
-- 注意：当前 poems.dynasty 全为空，此步骤为未来兼容
UPDATE authors a
SET dynasty = sub.dynasty
FROM (
    SELECT a.id AS author_id, p.dynasty
    FROM poems p
    JOIN authors a ON p.author_id = a.id
    WHERE p.dynasty IS NOT NULL
      AND p.dynasty != ''
      AND p.dynasty != '未知'
    GROUP BY a.id, p.dynasty
) sub
WHERE a.id = sub.author_id
  AND (a.dynasty IS NULL OR a.dynasty = '' OR a.dynasty = '未知');

